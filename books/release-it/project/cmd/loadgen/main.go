// Command loadgen is the lab's stand-in for tenants: an open-loop load
// generator (requests are sent at a fixed arrival rate whether or not earlier
// ones have answered) with named scenarios. It writes one CSV row per request
// and prints a JSON summary line at the end.
//
// It is also the platform's reference consumer: it reads responses strictly,
// with the exact field sets the API documents.
package main

import (
	"bytes"
	"encoding/csv"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"log"
	"math"
	"math/rand/v2"
	"net"
	"net/http"
	"os"
	"sort"
	"strconv"
	"sync"
	"sync/atomic"
	"time"
)

type dbEntry struct {
	Name string `json:"name"`
	ID   string `json:"id"`
	Node string `json:"node"`
}

type tenant struct {
	ID    string    `json:"id"`
	Key   string    `json:"key"`
	Class string    `json:"class"`
	DBs   []dbEntry `json:"dbs"`
}

type manifest struct {
	AdminKey string   `json:"admin_key"`
	Tenants  []tenant `json:"tenants"`
}

// The API's documented response shapes. The consumer reads them exactly.
type queryResp struct {
	Columns   []string `json:"columns"`
	Rows      [][]any  `json:"rows"`
	Truncated bool     `json:"truncated"`
}

type executeResp struct {
	RowsAffected    int64 `json:"rows_affected"`
	LastInsertRowID int64 `json:"last_insert_rowid"`
}

type createResp struct {
	ID         string `json:"id"`
	Name       string `json:"name"`
	Node       string `json:"node"`
	BytesTotal int64  `json:"bytes_total"`
	RowsTotal  int64  `json:"rows_total"`
	SizeBytes  int64  `json:"size_bytes"`
}

type usageResp struct {
	Window  string `json:"window"`
	Tenants []struct {
		TenantID     string `json:"tenant_id"`
		Statements   int64  `json:"statements"`
		Rows         int64  `json:"rows"`
		Bytes        int64  `json:"bytes"`
		StorageBytes int64  `json:"storage_bytes"`
	} `json:"tenants"`
}

type errorResp struct {
	Error struct {
		Code      string `json:"code"`
		Message   string `json:"message"`
		RequestID string `json:"request_id"`
	} `json:"error"`
}

type record struct {
	ts       int64
	route    string
	class    string
	node     string
	status   int
	latency  float64
	errClass string
	instance string
}

type gen struct {
	target   string
	scenario string
	client   *http.Client
	slow     *http.Client // the ops dashboard waits longer for its report
	m        manifest
	steady   []target // tenants' default databases, weighted
	weights  []float64
	cold     []target
	start    time.Time
	out      chan record
	seq      atomic.Int64
	seqBase  int64
	inflight sync.WaitGroup

	writeFrac float64
	errFrac   float64
	recursion int
}

type target struct {
	t  tenant
	db dbEntry
}

func main() {
	var (
		targetURL = flag.String("target", "http://haproxy:8080", "gateway or balancer URL")
		manPath   = flag.String("manifest", "/results/manifest.json", "seed manifest")
		scenario  = flag.String("scenario", "steady", "steady|errs|noisy|reports|whale|burst|create|rollout")
		rate      = flag.Float64("rate", 100, "steady arrival rate, requests per second")
		duration  = flag.Duration("duration", 60*time.Second, "run length")
		outPath   = flag.String("out", "/results/run.csv", "CSV output")
		timeout   = flag.Duration("timeout", 3*time.Second, "client timeout")
		writeFrac = flag.Float64("write-frac", 0.25, "fraction of steady requests that are writes")
		errFrac   = flag.Float64("err-frac", 0.3, "errs: fraction of writes that violate items.seq UNIQUE")
		extra     = flag.Int("extra", 0, "concurrency of the scenario's extra loops (noisy, reports, whale)")
		extraFrom = flag.Duration("extra-from", 0, "start the extra loops at this offset")
		extraFor  = flag.Duration("extra-for", 0, "run the extra loops this long (0: to the end)")
		coldRate  = flag.Float64("cold-rate", 0, "requests per second to databases outside the steady set")
		createR   = flag.Float64("create-rate", 0, "database creates per second")
		focus     = flag.String("focus", "", "tenant/db receiving extra writes (class target)")
		focusRate = flag.Float64("focus-rate", 10, "writes per second to the focus database")
		focusRows = flag.Int("focus-rows", 1, "rows each focus write inserts (a bulk insert holds the write lock longer)")
		node      = flag.String("node", "", "only send steady traffic to databases on this node")
		recursion = flag.Int("recursion", 3_000_000, "noisy: rows generated by each recursive query")
		seed      = flag.Uint64("seed", 1, "random seed")
		startAt   = flag.Int64("start-at", 0, "unix milliseconds at which to send the first request (aligns ts_ms with a script's timeline)")
	)
	flag.Parse()

	var m manifest
	data, err := os.ReadFile(*manPath)
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(data, &m); err != nil {
		log.Fatal(err)
	}
	rng = rand.New(rand.NewPCG(*seed, uint64(time.Now().UnixNano())))
	g := &gen{
		target: *targetURL, scenario: *scenario, m: m, out: make(chan record, 4096),
		writeFrac: *writeFrac, errFrac: *errFrac, recursion: *recursion,
		seqBase: time.Now().Unix() % 100000 * 1_000_000,
		client: &http.Client{
			Timeout: *timeout,
			Transport: &http.Transport{
				DialContext:         (&net.Dialer{Timeout: *timeout}).DialContext,
				MaxIdleConns:        4000,
				MaxIdleConnsPerHost: 4000,
				IdleConnTimeout:     30 * time.Second,
			},
		},
	}
	for _, t := range m.Tenants {
		if t.Class != "normal" {
			continue
		}
		for _, d := range t.DBs {
			if *node != "" && d.Node != *node {
				continue
			}
			if d.Name == "default" {
				g.steady = append(g.steady, target{t, d})
			} else {
				g.cold = append(g.cold, target{t, d})
			}
		}
	}
	if len(g.steady) == 0 {
		log.Fatal("no steady targets")
	}
	g.slow = &http.Client{Timeout: 10 * time.Second, Transport: g.client.Transport}
	// Mild skew: weight 1/sqrt(rank).
	total := 0.0
	for i := range g.steady {
		total += 1 / math.Sqrt(float64(i+1))
		g.weights = append(g.weights, total)
	}

	f, err := os.Create(*outPath)
	if err != nil {
		log.Fatal(err)
	}
	w := csv.NewWriter(f)
	w.Write([]string{"ts_ms", "scenario", "route", "tenant_class", "node", "status", "latency_ms", "err_class", "instance"})
	done := make(chan summary)
	go g.write(w, done)

	if *startAt > 0 {
		time.Sleep(time.Until(time.UnixMilli(*startAt)))
	}
	g.start = time.Now()
	end := g.start.Add(*duration)
	var wg sync.WaitGroup
	wg.Add(1)
	go func() { defer wg.Done(); g.openLoop(*rate, end, g.steadyRequest) }()
	if *coldRate > 0 {
		wg.Add(1)
		go func() { defer wg.Done(); g.openLoop(*coldRate, end, g.coldRequest) }()
	}
	if *createR > 0 {
		wg.Add(1)
		go func() { defer wg.Done(); g.openLoop(*createR, end, g.createRequest) }()
	}
	if *focus != "" {
		ft := g.find(*focus)
		wg.Add(1)
		go func() {
			defer wg.Done()
			g.openLoop(*focusRate, end, func() { g.writeN(ft, "target", *focusRows) })
		}()
	}
	if *extra > 0 {
		// Each extra loop is a client that backs off for as long as the
		// platform's Retry-After says when it is refused.
		var fn func() time.Duration
		switch *scenario {
		case "noisy":
			nt := g.special("noisy")
			fn = func() time.Duration {
				t := nt
				t.db = nt.t.DBs[rndInt(len(nt.t.DBs))] // the noisy tenant spreads over its databases
				return g.noisyQuery(t)
			}
		case "reports":
			fn = g.report
		case "whale":
			wt := g.special("whale")
			fn = func() time.Duration { return g.whaleScan(wt) }
		}
		if fn != nil {
			extraEnd := end
			if *extraFor > 0 {
				extraEnd = g.start.Add(*extraFrom + *extraFor)
			}
			for i := 0; i < *extra; i++ {
				wg.Add(1)
				go func() {
					defer wg.Done()
					time.Sleep(time.Until(g.start.Add(*extraFrom)))
					for time.Now().Before(extraEnd) {
						time.Sleep(fn())
					}
				}()
			}
		}
	}
	wg.Wait()
	g.inflight.Wait()
	close(g.out)
	s := <-done
	w.Flush()
	f.Close()
	s.Scenario, s.Rate, s.Seconds = *scenario, *rate, duration.Seconds()
	json.NewEncoder(os.Stdout).Encode(s)
}

var (
	rng   *rand.Rand
	rngMu sync.Mutex
)

func rnd() float64 {
	rngMu.Lock()
	defer rngMu.Unlock()
	return rng.Float64()
}

func rndInt(n int) int {
	rngMu.Lock()
	defer rngMu.Unlock()
	return rng.IntN(n)
}

// openLoop calls fn at rate per second until end, each call in its own
// goroutine, regardless of how long earlier calls take.
func (g *gen) openLoop(rate float64, end time.Time, fn func()) {
	start := time.Now()
	sent := 0
	tick := time.NewTicker(time.Millisecond)
	defer tick.Stop()
	for now := range tick.C {
		if now.After(end) {
			return
		}
		due := int(rate * now.Sub(start).Seconds())
		for ; sent < due; sent++ {
			g.inflight.Add(1)
			go func() { defer g.inflight.Done(); fn() }()
		}
	}
}

func (g *gen) pick() target {
	x := rnd() * g.weights[len(g.weights)-1]
	i := sort.SearchFloat64s(g.weights, x)
	if i >= len(g.steady) {
		i = len(g.steady) - 1
	}
	return g.steady[i]
}

func (g *gen) special(class string) target {
	for _, t := range g.m.Tenants {
		if t.Class == class {
			return target{t, t.DBs[0]}
		}
	}
	log.Fatalf("no %s tenant in manifest", class)
	return target{}
}

func (g *gen) find(spec string) target {
	for _, t := range g.m.Tenants {
		for _, d := range t.DBs {
			if t.ID+"/"+d.Name == spec {
				return target{t, d}
			}
		}
	}
	log.Fatalf("focus %s not in manifest", spec)
	return target{}
}

func (g *gen) steadyRequest() {
	tg := g.pick()
	if rnd() < g.writeFrac {
		if g.scenario == "errs" && rnd() < g.errFrac {
			g.violate(tg)
			return
		}
		g.write1(tg, "normal")
		return
	}
	g.read(tg, "normal")
}

func (g *gen) coldRequest() {
	if len(g.cold) == 0 {
		return
	}
	g.read(g.cold[rndInt(len(g.cold))], "cold")
}

func (g *gen) read(tg target, class string) {
	start := 1 + rndInt(990)
	g.do(tg, class, "query", map[string]any{
		"sql":  "SELECT id, seq, body, created_at FROM items WHERE id >= ? ORDER BY id LIMIT 10",
		"args": []any{start},
	}, new(queryResp))
}

func (g *gen) write1(tg target, class string) {
	seq := g.seqBase + g.seq.Add(1)
	g.do(tg, class, "execute", map[string]any{"statements": []map[string]any{{
		"sql":  "INSERT INTO notes (seq, body, created_at) VALUES (?, ?, datetime('now'))",
		"args": []any{seq, fmt.Sprintf("note %d from loadgen", seq)},
	}}}, new(executeResp))
}

// writeN inserts n notes rows in one statement.
func (g *gen) writeN(tg target, class string, n int) {
	if n <= 1 {
		g.write1(tg, class)
		return
	}
	base := g.seqBase + g.seq.Add(int64(n)) - int64(n)
	g.do(tg, class, "execute", map[string]any{"statements": []map[string]any{{
		"sql": `WITH RECURSIVE c(x) AS (SELECT 1 UNION ALL SELECT x + 1 FROM c WHERE x < ?)
			INSERT INTO notes (seq, body, created_at) SELECT ? + x, 'bulk note from loadgen', datetime('now') FROM c`,
		"args": []any{n, base},
	}}}, new(executeResp))
}

// violate inserts an items row whose seq already exists (seed rows 1..1000).
func (g *gen) violate(tg target) {
	g.do(tg, "errs", "execute", map[string]any{"statements": []map[string]any{{
		"sql":  "INSERT INTO items (seq, body, created_at) VALUES (?, 'dup', datetime('now'))",
		"args": []any{1 + rndInt(1000)},
	}}}, new(executeResp))
}

func (g *gen) noisyQuery(tg target) time.Duration {
	return g.do(tg, "noisy", "query", map[string]any{
		"sql":  "WITH RECURSIVE c(x) AS (SELECT 1 UNION ALL SELECT x + 1 FROM c WHERE x < ?) SELECT count(*), sum(x) FROM c",
		"args": []any{g.recursion},
	}, new(queryResp))
}

func (g *gen) whaleScan(tg target) time.Duration {
	return g.do(tg, "whale", "query", map[string]any{"sql": "SELECT * FROM events"}, new(queryResp))
}

// createRequest creates a database the way a new app does, then reads from
// it once.
func (g *gen) createRequest() {
	tg := g.pick()
	name := fmt.Sprintf("lg-%d-%d", time.Now().UnixNano()%1_000_000_000, rndInt(1000))
	var d createResp
	g.send(tg.t.Key, "create", "normal", "", http.MethodPost, "/v1/databases", map[string]any{"name": name}, &d)
	if d.Name == "" {
		return
	}
	g.do(target{tg.t, dbEntry{Name: d.Name, ID: d.ID, Node: d.Node}}, "cold", "query", map[string]any{"sql": "SELECT count(*) FROM _meta"}, new(queryResp))
}

func (g *gen) report() time.Duration {
	return g.send(g.m.AdminKey, "usage", "ops", "", http.MethodGet, "/v1/admin/usage?window=24h", nil, new(usageResp))
}

func (g *gen) do(tg target, class, op string, body any, out any) time.Duration {
	return g.send(tg.t.Key, op, class, tg.db.Node, http.MethodPost, "/v1/databases/"+tg.db.Name+"/"+op, body, out)
}

// send makes one request and records it; it returns how long the platform
// asked the client to wait before trying again (Retry-After), if it did.
func (g *gen) send(key, route, class, node, method, path string, body any, out any) time.Duration {
	var rd io.Reader
	if body != nil {
		b, _ := json.Marshal(body)
		rd = bytes.NewReader(b)
	}
	req, _ := http.NewRequest(method, g.target+path, rd)
	req.Header.Set("Authorization", "Bearer "+key)
	req.Header.Set("Content-Type", "application/json")
	t0 := time.Now()
	rec := record{ts: t0.Sub(g.start).Milliseconds(), route: route, class: class, node: node}
	client := g.client
	if route == "usage" {
		client = g.slow
	}
	resp, err := client.Do(req)
	if err != nil {
		rec.latency = ms(time.Since(t0))
		rec.errClass = "conn"
		var ne net.Error
		if errors.As(err, &ne) && ne.Timeout() {
			rec.errClass = "client_timeout"
		}
		g.out <- rec
		return 0
	}
	data, err := io.ReadAll(resp.Body)
	resp.Body.Close()
	rec.latency = ms(time.Since(t0))
	rec.status = resp.StatusCode
	rec.instance = resp.Header.Get("X-Served-By")
	switch {
	case err != nil:
		rec.errClass = "conn"
		var ne net.Error
		if errors.As(err, &ne) && ne.Timeout() {
			rec.errClass = "client_timeout"
		}
	case resp.StatusCode >= 200 && resp.StatusCode < 300:
		if len(data) > 0 && strict(data, out) != nil {
			rec.errClass = "decode"
		}
	default:
		var e errorResp
		if strict(data, &e) != nil || e.Error.Code == "" {
			rec.errClass = "http"
		} else {
			rec.errClass = e.Error.Code
		}
	}
	g.out <- rec
	if secs, err := strconv.Atoi(resp.Header.Get("Retry-After")); err == nil {
		return time.Duration(secs) * time.Second
	}
	return 0
}

// strict decodes exactly the documented fields.
func strict(data []byte, out any) error {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	return dec.Decode(out)
}

func ms(d time.Duration) float64 { return float64(d.Microseconds()) / 1000 }

type summary struct {
	Scenario string         `json:"scenario"`
	Rate     float64        `json:"rate"`
	Seconds  float64        `json:"seconds"`
	Sent     int            `json:"sent"`
	OK       int            `json:"ok"`
	Goodput  float64        `json:"goodput_rps"`
	P50      float64        `json:"p50_ms"`
	P99      float64        `json:"p99_ms"`
	Errors   map[string]int `json:"errors"`
}

func (g *gen) write(w *csv.Writer, done chan<- summary) {
	var s summary
	s.Errors = map[string]int{}
	var lat []float64
	for r := range g.out {
		w.Write([]string{
			strconv.FormatInt(r.ts, 10), g.scenario, r.route, r.class, r.node,
			strconv.Itoa(r.status), strconv.FormatFloat(r.latency, 'f', 3, 64), r.errClass, r.instance,
		})
		s.Sent++
		if r.errClass == "" && r.status >= 200 && r.status < 300 {
			s.OK++
			lat = append(lat, r.latency)
		} else {
			s.Errors[r.errClass+":"+strconv.Itoa(r.status)]++
		}
	}
	sort.Float64s(lat)
	if n := len(lat); n > 0 {
		s.P50 = lat[n/2]
		s.P99 = lat[min(n-1, n*99/100)]
	}
	s.Goodput = float64(s.OK) / math.Max(time.Since(g.start).Seconds(), 1)
	done <- s
}
